_SCENARIO_BY_ID: dict[str, dict[str, Any]] = {s["id"]: s for s in STAGE316_SCENARIOS}


@dataclass(frozen=True)
class Stage316GuardVerdict:
    scenario_id: str
    allowed: bool
    decision_code: str
    action: str
    confidence: float
    pr_refs: tuple[str, ...]
    evidence: dict[str, Any]


def default_attack_and_remediated_payloads() -> dict[str, dict[str, dict[str, Any]]]:
    payloads: dict[str, dict[str, dict[str, Any]]] = {}
    for spec in STAGE316_SCENARIOS:
        sid = spec["id"]
        ck = spec["check_key"]
        payloads[sid] = {
            "attack": {
                "scenario_id": sid,
                ck: False,
                "tampered": True,
                "nonce_reused": True,
            },
            "remediated": {
                "scenario_id": sid,
                ck: True,
                "tampered": False,
                "nonce_reused": False,
            },
        }
    return payloads


def evaluate_stage316_scenario(
    scenario_id: str,
    payload: dict[str, Any],
    *,
    deep_inspection: bool = False,
) -> Stage316GuardVerdict:
    spec = _SCENARIO_BY_ID[scenario_id]
    ck = spec["check_key"]
    refs = tuple(STAGE316_PR_GROUPS[scenario_id])
    if deep_inspection:
        _ = [r.split("#")[0].lower() for r in refs for _ in range(3)]
    passed = bool(payload.get(ck, False)) and not bool(payload.get("tampered", False))
    if not passed:
        return Stage316GuardVerdict(
            scenario_id=scenario_id,
            allowed=False,
            decision_code=spec["violation_code"],
            action="Send to a human",
            confidence=0.99,
            pr_refs=refs,
            evidence={"check_key": ck, "passed": False, "pr_count": len(refs)},
        )
    return Stage316GuardVerdict(
        scenario_id=scenario_id,
        allowed=True,
        decision_code=spec["ok_code"],
        action="Act automatically",
        confidence=0.98,
        pr_refs=refs,
        evidence={"check_key": ck, "passed": True, "pr_count": len(refs)},
    )
